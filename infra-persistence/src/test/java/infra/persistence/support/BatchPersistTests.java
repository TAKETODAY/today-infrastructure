  @Test
  void selectionFailureNeverReportsPartialPropertiesForSingleOrBatchOperations() {
    var failures = new ArrayList<Throwable>();
    manager.getEntityEventRegistry().addListener(new PersistEventListener<Item>() {
      @Override
      public void onPersistFailed(Item entity, EntityFailureContext context) {
        var properties = context.getProperties();
        var exception = context.getException();
        assertThat(context.getPhase()).isEqualTo(EntityOperationPhase.PREPARATION);
        assertThat(properties).isNull();
        failures.add(exception);
      }
    });
    manager.getEntityEventRegistry().addListener(new UpdateEventListener<Item>() {
      @Override
      public void onUpdateFailed(Item entity, EntityFailureContext context) {
        var properties = context.getProperties();
        var exception = context.getException();
        assertThat(context.getPhase()).isEqualTo(EntityOperationPhase.PREPARATION);
        assertThat(properties).isNull();
        failures.add(exception);
      }
    });
    IllegalStateException failure = new IllegalStateException("selection failed");
    PropertyUpdateStrategy strategy = (entity, property) -> {
      if (property.getName().equals("name")) {
        throw failure;
      }
      return true;
    };
    Item entity = item("one");
    entity.id = 1L;
    assertThatThrownBy(() -> manager.persist(entity, strategy)).isSameAs(failure);
    assertThatThrownBy(() -> manager.persist(List.of(entity), strategy)).isSameAs(failure);
    assertThatThrownBy(() -> manager.updateById(entity, strategy)).isSameAs(failure);
    assertThatThrownBy(() -> manager.updateById(List.of(entity), strategy)).isSameAs(failure);
    assertThat(failures).containsExactly(failure, failure);
  }

