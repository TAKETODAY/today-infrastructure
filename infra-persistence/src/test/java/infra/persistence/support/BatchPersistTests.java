  static class RecordingManager extends DefaultEntityManager {
    int[] results;
    ResultSet keys;
    PreparedStatement statement;

    RecordingManager(RepositoryManager repository) {
      super(repository);
    }

    @Override
    protected PreparedStatement prepareStatement(Connection connection, String sql, boolean generatedKeys) throws SQLException {
      statement = spy(connection.prepareStatement(sql, generatedKeys ? Statement.RETURN_GENERATED_KEYS : Statement.NO_GENERATED_KEYS));
      if (results != null) {
        given(statement.executeBatch()).willReturn(results);
        given(statement.getGeneratedKeys()).willReturn(mock(ResultSet.class));
      }
      if (keys != null) {
        given(statement.getGeneratedKeys()).willReturn(keys);
      }
      return statement;
    }
  }
